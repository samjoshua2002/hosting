// Embeds src/agent/hostctl.sh into a TS module so the server can upload it to VMs.
// The version is a hash of the script, so any edit makes the dashboard update every VM's agent.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const srcPath = new URL("../src/agent/hostctl.sh", import.meta.url);
const outPath = new URL("../src/lib/agent-script.generated.ts", import.meta.url);

const src = readFileSync(srcPath, "utf8");
const version = createHash("sha256").update(src).digest("hex").slice(0, 12);
const script = src.replace("__AGENT_VERSION__", version);

const out =
  "// Generated by scripts/gen-agent.mjs from src/agent/hostctl.sh. Do not edit by hand.\n" +
  `export const AGENT_VERSION = ${JSON.stringify(version)};\n` +
  `export const AGENT_SCRIPT = ${JSON.stringify(script)};\n`;

if (!existsSync(outPath) || readFileSync(outPath, "utf8") !== out) {
  writeFileSync(outPath, out);
  console.log(`agent script embedded (version ${version})`);
}

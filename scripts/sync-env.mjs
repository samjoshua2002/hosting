// Builds .env.local from tokens.txt and prints the block to paste into Vercel.
//   node scripts/sync-env.mjs            update .env.local, print what changed
//   node scripts/sync-env.mjs --print    also print the full env block for Vercel
// Existing ADMIN_PASSWORD / SESSION_SECRET in .env.local are kept; missing ones are generated.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync, chmodSync } from "node:fs";

const root = new URL("../", import.meta.url);
const tokensPath = new URL("tokens.txt", root);
const envPath = new URL(".env.local", root);
const INSTABOX_HOST_KEY = "DQYkbhc9iBYcfVvhXZBsT9qhzAyLvLIyjmm57Vimfxk"; // ssh.instabox.sh:2222 ED25519, checked 2026-11-07

if (!existsSync(tokensPath)) {
  console.error("tokens.txt not found. Put one InstaBox ibssh_… username per line in it.");
  process.exit(1);
}

const tokens = readFileSync(tokensPath, "utf8")
  .split("\n")
  .filter((l) => l.trim() && !l.trim().startsWith("#"))
  .map((l) => l.match(/ibssh_[A-Za-z0-9]+/)?.[0])
  .filter(Boolean);
if (!tokens.length) {
  console.error("No ibssh_ tokens found in tokens.txt.");
  process.exit(1);
}

const env = new Map();
if (existsSync(envPath)) {
  for (const line of readFileSync(envPath, "utf8").split("\n")) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) env.set(m[1], m[2].replace(/^"(.*)"$/, "$1"));
  }
}

const generated = [];
if (!env.get("ADMIN_PASSWORD")) {
  env.set("ADMIN_PASSWORD", randomBytes(18).toString("base64url"));
  generated.push("ADMIN_PASSWORD");
}
if (!env.get("SESSION_SECRET") || env.get("SESSION_SECRET").length < 16) {
  env.set("SESSION_SECRET", randomBytes(32).toString("base64url"));
  generated.push("SESSION_SECRET");
}
if (!env.get("CRON_SECRET")) {
  env.set("CRON_SECRET", randomBytes(24).toString("base64url"));
  generated.push("CRON_SECRET");
}
env.set("INSTABOX_HOST_KEY_SHA256", env.get("INSTABOX_HOST_KEY_SHA256") || INSTABOX_HOST_KEY);
// Always-on servers (name=user@host:port), e.g. written by scripts/oracle-free-vm.sh
const serversPath = new URL("servers.txt", root);
const servers = existsSync(serversPath)
  ? readFileSync(serversPath, "utf8")
      .split("\n")
      .map((l) => l.trim())
      .filter((l) => /^[a-z0-9][a-z0-9-]{0,31}=[^@\s]+@[^\s:]+(:\d{1,5})?$/.test(l))
  : [];
env.set("VMS", [...tokens.map((t, i) => `box${i + 1}=${t}`), ...servers].join(","));

const order = ["ADMIN_PASSWORD", "SESSION_SECRET", "CRON_SECRET", "PASSWORD_LOGIN", "PASSKEYS", "APP_URL", "VMS", "SSH_PRIVATE_KEY_B64", "INSTABOX_HOST_KEY_SHA256"];
const keys = [...order.filter((k) => env.has(k)), ...[...env.keys()].filter((k) => !order.includes(k))];
const body = keys.map((k) => `${k}="${env.get(k)}"`).join("\n") + "\n";
writeFileSync(envPath, "# Generated by scripts/sync-env.mjs. Do not commit.\n" + body);
chmodSync(envPath, 0o600);

console.log(`.env.local updated: ${tokens.length} InstaBox VMs (box1..box${tokens.length})${servers.length ? ` + ${servers.length} server(s): ${servers.map((x) => x.split("=")[0]).join(", ")}` : ""}.`);
if (generated.length) console.log(`Generated: ${generated.join(", ")}`);
console.log(`Login password: ${env.get("ADMIN_PASSWORD")}`);
if (process.argv.includes("--print")) {
  console.log("\nPaste this into Vercel → Project → Settings → Environment Variables (it accepts a whole .env block):\n");
  console.log(body);
} else {
  console.log("Run `npm run env:sync -- --print` to print the block for Vercel. After changing env vars on Vercel, redeploy.");
}
